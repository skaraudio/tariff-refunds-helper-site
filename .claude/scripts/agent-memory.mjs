#!/usr/bin/env node
/**
 * agent-memory — keeps this repository's shared subagent memory (`.claude/agent-memory/<agent>/`)
 * consistent and reviewable. Protocol: `.claude/skills/agent-memory/SKILL.md`.
 *
 *   node .claude/scripts/agent-memory.mjs index [agent]            Regenerate MEMORY.md from topic-file
 *                                                                   frontmatter (all agents, or one).
 *   node .claude/scripts/agent-memory.mjs check [agent] [--verify] Lint the stores; --verify also runs
 *                                                                   each memory's read-only `verify`
 *                                                                   (parsed and run without a shell).
 *
 * Errors (exit 1) must be fixed before memory changes are committed; warnings need a look. Works from
 * any folder: the repository root is found from this script's location. A "store" is the
 * `.claude/agent-memory/` folder beside a `.claude/agents/` folder. Any other agent-memory folder that
 * holds files is a stray (usually from a session launched in a subdirectory), and
 * `.claude/agent-memory-local/` is never used: shared memory must hold on every machine. `index` never
 * overwrites a MEMORY.md holding hand-written lines (a legacy index or inline facts); `check` reports
 * E_LEGACY_INDEX until those facts live in topic files. No dependencies; Node 18+.
 */

import {spawnSync} from 'node:child_process';
import {existsSync, lstatSync, readdirSync, readFileSync, statSync, writeFileSync} from 'node:fs';
import {hostname} from 'node:os';
import {basename, dirname, join, relative, sep} from 'node:path';
import {fileURLToPath} from 'node:url';

function repoRoot() {
	const here = dirname(fileURLToPath(import.meta.url));
	if (basename(here) === 'scripts' && basename(dirname(here)) === '.claude') return dirname(dirname(here));
	const r = spawnSync('git', ['rev-parse', '--show-toplevel'], {encoding: 'utf8'});
	return r.status === 0 ? r.stdout.trim() : process.cwd();
}

const ROOT = repoRoot();
const PRUNE = new Set(['node_modules', '.git', '.next', 'dist', 'build', '.vercel', 'vendor', 'coverage', 'temp', 'worktrees']);
const TYPES = ['project', 'feedback', 'reference'];
const INDEX_HEADER = '<!-- Generated by `node .claude/scripts/agent-memory.mjs index`. Edit topic files, not this index. -->';
const MAX_INDEX_LINE = 150;
const MAX_ENTRIES = 60;
const MAX_TOPIC_BYTES = 4096;
const STALE_DAYS = 90;

const rel = (p) => relative(ROOT, p).split(sep).join('/');
const lf = (s) => s.replace(/\r\n/g, '\n').replace(/^\uFEFF/, '');
const isFixture = (p) => /\/(test|tests|fixtures|__fixtures__|snapshots)\//.test('/' + rel(p) + '/');
const hasFiles = (dir) => {
	try {
		return readdirSync(dir, {withFileTypes: true}).some((e) => (e.isDirectory() ? hasFiles(join(dir, e.name)) : true));
	} catch {
		return false;
	}
};

/** Every `.claude` folder in the repo (pruned walk). */
function claudeDirs(dir = ROOT, out = []) {
	let entries;
	try {
		entries = readdirSync(dir, {withFileTypes: true});
	} catch {
		return out;
	}
	for (const e of entries) {
		if (!e.isDirectory() || PRUNE.has(e.name)) continue;
		const p = join(dir, e.name);
		if (e.name === '.claude') out.push(p);
		else claudeDirs(p, out);
	}
	return out;
}

function discover() {
	const stores = [];
	const strays = [];
	for (const c of claudeDirs()) {
		if (isFixture(c)) continue;
		const mem = join(c, 'agent-memory');
		const st = lstatSync(mem, {throwIfNoEntry: false});
		if (st && !st.isDirectory()) strays.push(mem); // a link or file is never a store
		else if (st) {
			if (existsSync(join(c, 'agents'))) stores.push(mem);
			// Claude Code creates an empty agent-memory folder on a subdirectory launch; only a stray
			// that holds files matters.
			else if (hasFiles(mem)) strays.push(mem);
		}
		const local = join(c, 'agent-memory-local');
		if (existsSync(local) && hasFiles(local)) strays.push(local);
	}
	return {stores, strays};
}

// Claude Code auto-creates an empty agent folder at spawn; only a folder holding files is a store.
function agentDirs(store, only) {
	return readdirSync(store, {withFileTypes: true})
		.filter((e) => e.isDirectory() && (!only || e.name === only))
		.map((e) => join(store, e.name))
		.filter(hasFiles);
}

/** Minimal frontmatter parser: top-level `key: value`, plus `metadata:` children. */
function parse(text) {
	const t = lf(text);
	const m = /^---\n([\s\S]*?)\n---(?:\n|$)/.exec(t);
	if (!m) return {fm: null, body: t};
	const fm = {};
	let parent = null;
	for (const line of m[1].split('\n')) {
		const kv = /^(\s*)([A-Za-z_][\w-]*):\s*(.*)$/.exec(line);
		if (!kv) continue;
		const [, indent, key, raw] = kv;
		const val = raw.trim().replace(/^(["'])(.*)\1$/, '$2').trim(); // a matched pair of quotes only
		if (!indent && val === '') {
			parent = key;
			fm[key] = fm[key] || {};
		} else if (indent && parent && typeof fm[parent] === 'object') fm[parent][key] = val;
		else {
			parent = null;
			fm[key] = val;
		}
	}
	return {fm, body: t.slice(m[0].length)};
}

// Protocol fields live under `metadata:`; top-level copies (older notes) are accepted.
const field = (fm, key) => (fm && (fm.metadata?.[key] ?? fm[key])) || '';

function topics(agentDir) {
	return readdirSync(agentDir, {withFileTypes: true})
		.filter((e) => e.isFile() && e.name.endsWith('.md') && e.name !== 'MEMORY.md') // symlinks are errors in check
		.map((e) => e.name)
		.sort()
		.map((f) => {
			const path = join(agentDir, f);
			const text = readFileSync(path, 'utf8');
			return {file: f, path, text, bytes: Buffer.byteLength(text), ...parse(text)};
		});
}

function buildIndex(agentDir) {
	const agent = basename(agentDir);
	const items = topics(agentDir);
	const out = [INDEX_HEADER, `# ${agent} memory`, ''];
	const title = (t) => field(t.fm, 'name') || t.file;
	for (const type of TYPES) {
		const group = items.filter((t) => field(t.fm, 'type') === type);
		if (!group.length) continue;
		out.push(`## ${type[0].toUpperCase()}${type.slice(1)}`);
		// Plain code-unit order, so every machine generates the same index.
		for (const t of group.sort((a, b) => (title(a) < title(b) ? -1 : title(a) > title(b) ? 1 : 0))) {
			let line = `- [${title(t)}](${t.file}) — ${field(t.fm, 'description')}`.trimEnd();
			// Cut by code points, so an emoji is never split into a lone surrogate.
			if (line.length > MAX_INDEX_LINE) line = cut(line, MAX_INDEX_LINE - 1) + '…';
			out.push(line);
		}
		out.push('');
	}
	const untyped = items.filter((t) => !TYPES.includes(field(t.fm, 'type')));
	if (untyped.length) {
		out.push('## Needs a valid type (see check)');
		for (const t of untyped) out.push(`- [${t.file}](${t.file})`);
		out.push('');
	}
	return out.join('\n').replace(/\n+$/, '\n');
}

/** The first `max` UTF-16 units of `s`, never ending inside a surrogate pair. */
function cut(s, max) {
	let out = '';
	for (const ch of s) {
		if (out.length + ch.length > max) break;
		out += ch;
	}
	return out;
}

/**
 * Lines of an existing MEMORY.md that `index` would discard. A generated index (first line is
 * INDEX_HEADER) holds only headings and `- [name](file.md)` links; anything else was hand-written. A
 * legacy index (no header) counts whole, because its hooks may carry facts no topic file has.
 */
function handWritten(agentDir) {
	const idx = join(agentDir, 'MEMORY.md');
	if (!lstatSync(idx, {throwIfNoEntry: false})?.isFile()) return [];
	const lines = lf(readFileSync(idx, 'utf8')).split('\n');
	const generated = lines[0] === INDEX_HEADER;
	const link = /^- \[[^\]]*\]\([^)\s]+\.md\)/;
	return lines.filter((l) => l.trim() && l !== INDEX_HEADER && !/^#{1,6}\s/.test(l) && !(generated && link.test(l)));
}

